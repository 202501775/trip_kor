def as_place(item, category, source="샘플"):
    name, address, lat, lon = item
    return {
        "name": name,
        "address": address,
        "lat": lat,
        "lon": lon,
        "category": category,
        "phone": "",
        "url": f"https://map.kakao.com/link/search/{name}",
        "source": source,
    }


def get_sample_places(region):
    key = next((name for name in SAMPLE_PLACES if name in region), "서울")
